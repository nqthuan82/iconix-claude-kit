# ── main() exit codes ───────────────────────────────────────────────────────
def run(argv):
    try:
        return promote.main(argv)
    except SystemExit as exc:
        return exc.code


def test_main_exit_0_on_success(tmp_path):
    cfg = setup_project(tmp_path)
    (tmp_path / "use-cases" / "UC-DRAFT-001-checkout.md").write_text(uc("UC-DRAFT-001"), encoding="utf-8")
    assert run(["--args", "all", "--config", cfg]) == _common.EXIT_OK


def test_main_exit_1_when_nothing_eligible(tmp_path):
    cfg = setup_project(tmp_path)
    assert run(["--args", "all", "--config", cfg]) == _common.EXIT_GATE


